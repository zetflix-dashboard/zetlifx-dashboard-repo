const SQL0 = [
  'WITH quarter_filter AS (SELECT CAST(? AS DATE) AS first, CAST(? AS DATE) AS last, CAST(? AS VARCHAR) AS quarter)',
  'SELECT',
  '  CAST(period AS VARCHAR) AS period,',
  '  CAST(net_revenue AS DOUBLE) AS net_revenue,',
  '  CAST(operating_profit AS DOUBLE) AS operating_profit,',
  '  CAST(100.0 * operating_profit / NULLIF(net_revenue, 0) AS DOUBLE) AS margin_pct',
  "FROM read_parquet('pl_control.parquet') CROSS JOIN quarter_filter f",
  'WHERE period >= f.first AND period <= f.last',
  "  AND (f.quarter = 'all' OR date_part('quarter', period) = try_cast(f.quarter AS INTEGER))",
  'ORDER BY period',
].join('\n');
const SQL1 = [
  'WITH ads AS (',
  '  SELECT period, SUM(revenue) AS revenue, SUM(impressions) AS impressions',
  "  FROM read_parquet('ad_revenue.parquet') GROUP BY period",
  ')',
  'SELECT',
  '  CAST(i.period AS VARCHAR) AS period,',
  '  CAST(100.0 * i.sold_impressions / NULLIF(i.available_impressions, 0) AS DOUBLE) AS fill_pct,',
  '  CAST(1000.0 * a.revenue / NULLIF(a.impressions, 0) AS DOUBLE) AS ecpm',
  "FROM read_parquet('ad_inventory.parquet') AS i",
  'LEFT JOIN ads AS a USING (period)',
  'WHERE i.period >= CAST(? AS DATE) AND i.period <= CAST(? AS DATE)',
  'ORDER BY i.period',
].join('\n');

// C15: subscription-access viewing hours, independently aggregated before joining titles.
const SQL_C15 = [
  'WITH selection AS (SELECT CAST(? AS DATE) AS first, CAST(? AS DATE) AS last, CAST(? AS VARCHAR) AS access), watch AS (',
  '  SELECT v.title_id, SUM(v.hours_watched) AS hours',
  "  FROM read_parquet('viewing_daily.parquet') v",
  "  JOIN read_parquet('users.parquet') u USING (user_id)",
  '  CROSS JOIN selection f',
  '  WHERE v.view_date >= f.first AND v.view_date <= last_day(f.last)',
  "    AND NOT u.is_test AND v.access_type IN ('Подписка', 'Пробный период', 'Партнерский пакет')",
  "    AND (f.access = 'all' OR v.access_type = f.access)",
  '  GROUP BY v.title_id',
  ')',
  'SELECT CAST(t.origin AS VARCHAR) AS origin, CAST(SUM(w.hours) AS DOUBLE) AS hours',
  "FROM watch w JOIN read_parquet('content_titles.parquet') t USING (title_id)",
  'GROUP BY t.origin ORDER BY hours DESC',
].join('\n');

// C14: amortization and viewing are separate monthly fact grains: aggregate prior to joining.
const SQL_C14 = [
  'WITH bounds AS (SELECT CAST(? AS DATE) AS first, CAST(? AS DATE) AS last, CAST(? AS VARCHAR) AS genre),',
  'amort AS (',
  '  SELECT a.title_id, SUM(a.amortization_amount) AS expense',
  "  FROM read_parquet('content_amortization.parquet') a CROSS JOIN bounds b",
  '  WHERE a.period >= b.first AND a.period <= b.last',
  '  GROUP BY a.title_id',
  '), watch AS (',
  '  SELECT v.title_id, SUM(v.hours_watched) AS hours',
  "  FROM read_parquet('viewing_daily.parquet') v",
  "  JOIN read_parquet('users.parquet') u USING (user_id)",
  '  CROSS JOIN bounds b',
  '  WHERE v.view_date >= b.first AND v.view_date <= last_day(b.last)',
  "    AND NOT u.is_test AND v.access_type IN ('Подписка', 'Пробный период', 'Партнерский пакет')",
  '  GROUP BY v.title_id',
  ')',
  'SELECT CAST(t.title_name AS VARCHAR) AS title, CAST(w.hours AS DOUBLE) AS hours,',
  '  CAST(a.expense / NULLIF(w.hours, 0) AS DOUBLE) AS cost_per_hour',
  "FROM amort a JOIN watch w USING (title_id) JOIN read_parquet('content_titles.parquet') t USING (title_id) CROSS JOIN bounds b",
  "WHERE w.hours > 0 AND (b.genre = 'all' OR t.genre = b.genre) ORDER BY hours DESC",
].join('\n');

// C20: fixed 31.12.2025 snapshot. No shared period filter is applicable.
const SQL_C20 = [
  'WITH paid AS (',
  '  SELECT b.user_id, b.service_period_start, b.service_period_end,',
  '    CAST(b.charged_amount AS DOUBLE) AS amount',
  "  FROM read_parquet('billing_events.parquet') b",
  "  JOIN read_parquet('users.parquet') u USING (user_id)",
  "  WHERE b.event_status = 'Успешно' AND NOT b.is_test AND NOT u.is_test",
  "    AND u.account_type = 'Прямой пользователь' AND b.plan_id IN ('PL1', 'PL2')",
  "    AND b.event_date BETWEEN DATE '2024-01-01' AND DATE '2025-12-31'",
  '), money AS (',
  '  SELECT user_id, SUM(amount) AS amount FROM paid GROUP BY user_id',
  '), frequency AS (',
  '  SELECT p.user_id, COUNT(DISTINCT CAST(m.month AS DATE)) AS months',
  '  FROM paid p, UNNEST(generate_series(',
  "    date_trunc('month', p.service_period_start),",
  "    date_trunc('month', p.service_period_end), INTERVAL 1 MONTH",
  '  )) AS m(month)',
  "  WHERE m.month BETWEEN DATE '2024-01-01' AND DATE '2025-12-01'",
  '  GROUP BY p.user_id',
  '), last_view AS (',
  '  SELECT v.user_id, MAX(v.view_date) AS last_date',
  "  FROM read_parquet('viewing_daily.parquet') v",
  '  JOIN money mo USING (user_id)',
  "  WHERE v.view_date <= DATE '2025-12-31'",
  '  GROUP BY v.user_id',
  '), scored AS (',
  '  SELECT mo.user_id, mo.amount,',
  '    COALESCE(f.months, 0) AS paid_months,',
  "    CASE WHEN lv.last_date IS NULL THEN NULL ELSE date_diff('day', lv.last_date, DATE '2025-12-31') END AS days_since_view,",
  '    CASE WHEN lv.last_date IS NULL THEN 1 ELSE 0 END AS never_viewed,',
  "    CASE WHEN lv.last_date IS NULL OR date_diff('day', lv.last_date, DATE '2025-12-31') > 90 THEN 1",
  "         WHEN date_diff('day', lv.last_date, DATE '2025-12-31') > 30 THEN 2 ELSE 3 END AS r,",
  '    CASE WHEN COALESCE(f.months, 0) >= 12 THEN 3',
  '         WHEN COALESCE(f.months, 0) >= 4 THEN 2 ELSE 1 END AS f,',
  '    CASE WHEN mo.amount >= 5000 THEN 3 WHEN mo.amount >= 1500 THEN 2 ELSE 1 END AS m',
  '  FROM money mo LEFT JOIN frequency f USING (user_id)',
  '  LEFT JOIN last_view lv USING (user_id)',
  '), groups AS (',
  '  SELECT r, f, m, COUNT(*) AS users, SUM(amount) AS revenue,',
  '    AVG(paid_months) AS avg_paid_months,',
  '    AVG(days_since_view) AS avg_days_since_view,',
  '    SUM(never_viewed) AS never_viewed_users',
  '  FROM scored GROUP BY r, f, m',
  ')',
  'SELECT CAST(r AS VARCHAR) || CAST(f AS VARCHAR) || CAST(m AS VARCHAR) AS segment,',
  '  CAST(r AS DOUBLE) AS recency_score, CAST(f AS DOUBLE) AS frequency_score,',
  '  CAST(m AS DOUBLE) AS monetary_score, CAST(users AS DOUBLE) AS users,',
  '  CAST(revenue AS DOUBLE) AS revenue,',
  '  CAST(100.0 * users / NULLIF(SUM(users) OVER (), 0) AS DOUBLE) AS user_share_pct,',
  '  CAST(100.0 * revenue / NULLIF(SUM(revenue) OVER (), 0) AS DOUBLE) AS share_pct,',
  '  CAST(revenue / NULLIF(users, 0) AS DOUBLE) AS revenue_per_user,',
  '  CAST(avg_paid_months AS DOUBLE) AS avg_paid_months,',
  '  CAST(avg_days_since_view AS DOUBLE) AS avg_days_since_view,',
  '  CAST(never_viewed_users AS DOUBLE) AS never_viewed_users',
  'FROM groups ORDER BY revenue DESC',
].join('\n');

